'use strict';
// build-soul.js — collects the MANUAL skins from scripts/skins/soul/NNN-*.js
// straight into src/renderer/data/skin-presets.ts (the schema the UI really uses).
const fs = require('fs'), path = require('path');
const { execFileSync } = require('child_process');

const soulDir = __dirname + path.sep + 'soul';
const root = path.resolve(__dirname, '..', '..');
const tmpDir = path.join(root, 'tmp_skins_build');
const resourcesSkins = path.join(root, 'resources', 'skins');
const rendererTs = path.join(root, 'src', 'renderer', 'data', 'skin-presets.ts');

fs.mkdirSync(tmpDir, { recursive: true });
fs.mkdirSync(resourcesSkins, { recursive: true });

const files = fs.readdirSync(soulDir).filter(f => /^\d{3}-.*\.js$/.test(f)).sort();
if (!files.length) { console.error('No soul skin scripts found'); process.exit(1); }

function extractMeta(txt) {
  const m = txt.match(/module\.exports\s*=\s*\{\s*meta:\s*(\{[\s\S]*?\})\s*\}\s*;?/);
  if (!m) return null;
  return (new Function('return (' + m[1] + ')'))();
}

const presets = [];
const seen = new Set();
for (const f of files) {
  const full = path.join(soulDir, f);
  const meta = extractMeta(fs.readFileSync(full, 'utf8'));
  if (!meta || !meta.id) { console.warn('skip (no meta): ' + f); continue; }
  if (seen.has(meta.id)) { console.warn('duplicate id skipped: ' + meta.id); continue; }
  seen.add(meta.id);
  const png = path.join(tmpDir, meta.id + '.png');
  execFileSync(process.execPath, [full, png], { stdio: 'pipe' });
  const buf = fs.readFileSync(png);
  fs.writeFileSync(path.join(resourcesSkins, meta.id + '.png'), buf);
  const cat = (['male','female','neutral'].includes(meta.gender)) ? meta.gender : 'neutral';
  const style = (['cyber','fantasy','pastel'].includes(meta.style)) ? meta.style : 'cyber';
  presets.push({
    id: meta.id,
    name: meta.nameEn || meta.id,
    nameRu: meta.nameRu || '',
    category: cat,
    description: meta.role || '',
    model: meta.model === 'slim' ? 'slim' : 'classic',
    style: style,
    dataUrl: 'data:image/png;base64,' + buf.toString('base64'),
  });
  console.log('built ' + meta.id + '  (' + style + '/' + cat + ')');
}

const header =
  '// AUTO-GENERATED by scripts/skins/build-soul.js — DO NOT EDIT BY HAND.\n' +
  '// ' + presets.length + ' hand-crafted skins from scripts/skins/soul/.\n\n' +
  'export interface SkinPreset {\n' +
  '  id: string;\n  name: string;\n  nameRu?: string;\n' +
  "  category: 'male' | 'female' | 'neutral';\n" +
  '  description: string;\n' +
  "  model: 'classic' | 'slim';\n" +
  "  style: 'cyber' | 'fantasy' | 'pastel';\n" +
  '  dataUrl: string;\n}\n\n' +
  'export const SKIN_PRESETS: SkinPreset[] = ';

fs.writeFileSync(rendererTs, header + JSON.stringify(presets, null, 2) + ';\n', 'utf8');

// cleanup temp
try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (e) {}

const byTheme = {};
for (const p of presets) { const k = p.style + '/' + p.category; byTheme[k] = (byTheme[k]||0)+1; }
console.log('\nWrote ' + presets.length + ' presets -> src/renderer/data/skin-presets.ts');
console.log('Themes: ' + JSON.stringify(byTheme));
